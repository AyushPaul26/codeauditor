import { describe, expect, it } from "vitest";
import type { WorkspaceAdapter, DocumentSnapshot } from "../../src/contracts";
import { retrieveContext, searchWorkspace } from "../../src/context/retrieve";
import { parseMentions } from "../../src/context/mentions";
import { calculateContextBudget } from "../../src/context/budget";

function memoryWorkspace(
  files: Record<string, string>,
): WorkspaceAdapter & { files: Record<string, string>; reads: string[] } {
  const reads: string[] = [];
  return {
    root: "/test/project",
    files,
    reads,
    async listFiles() {
      return Object.keys(files);
    },
    async read(file): Promise<DocumentSnapshot> {
      reads.push(file);
      if (!(file in files)) throw new Error("File unavailable");
      return { path: file, text: files[file], version: files[file] };
    },
    async apply() {
      throw new Error("Retrieval must never write");
    },
  };
}

describe("workspace context retrieval", () => {
  it("parses explicit file paths containing spaces and symbol mentions", () => {
    expect(
      parseMentions(
        'Read @file:"src/my file.py" and @symbol:loadConfig and @file(docs/usage.md)',
      ),
    ).toEqual([
      { kind: "file", value: "src/my file.py" },
      { kind: "symbol", value: "loadConfig" },
      { kind: "file", value: "docs/usage.md" },
    ]);
  });

  it("resolves an explicit file from the current adapter snapshot, including unsaved CRLF changes", async () => {
    const adapter = memoryWorkspace({
      "src/my file.py": 'def configure():\r\n    return "saved"\r\n',
    });
    await retrieveContext(adapter, 'Read @file:"src/my file.py"');
    adapter.files["src/my file.py"] =
      'def configure():\r\n    return "unsaved"\r\n';
    const result = await retrieveContext(
      adapter,
      'Read @file:"src/my file.py"',
    );
    expect(result.snippets).toHaveLength(1);
    expect(result.snippets[0]).toMatchObject({
      path: "src/my file.py",
      startLine: 1,
      endLine: 3,
    });
    expect(result.snippets[0].text).toContain('"unsaved"');
    expect(result.snippets[0].reason).toMatch(/explicit file/i);
  });

  it("prioritizes a symbol definition over a mention and falls back to literal text for unknown syntax", async () => {
    const adapter = memoryWorkspace({
      "a-caller.ts": "configure(options);",
      "src/settings.ts":
        "export function configure(options: unknown) {\n  return options;\n}",
      "rules/custom.rule": "unusual-handler -> call-with-value",
    });
    const definitions = await retrieveContext(
      adapter,
      "Explain @symbol:configure",
    );
    expect(definitions.snippets[0]).toMatchObject({
      path: "src/settings.ts",
      startLine: 1,
    });
    expect(definitions.snippets[0].reason).toMatch(/symbol definition/i);
    const fallback = await retrieveContext(
      adapter,
      "Explain @symbol:unusual-handler",
    );
    expect(fallback.snippets[0]).toMatchObject({ path: "rules/custom.rule" });
    expect(fallback.snippets[0].reason).toMatch(/symbol text/i);
  });

  it("keeps the requested symbol visible when preceding lines exceed the available budget", async () => {
    const lines = Array.from(
      { length: 12 },
      (_, index) => `const filler${index} = "${"x".repeat(1800)}";`,
    );
    const adapter = memoryWorkspace({
      "src/settings.ts": [
        ...lines,
        "export function configure() { return true; }",
      ].join("\n"),
    });
    const result = await retrieveContext(
      adapter,
      "Explain @symbol:configure",
      2400,
    );
    expect(result.snippets[0].text).toContain("function configure");
    expect(result.snippets[0].startLine).toBeLessThanOrEqual(13);
    expect(result.snippets[0].endLine).toBeGreaterThanOrEqual(13);
  });

  it("retains separate explicitly requested symbol windows in the same file", async () => {
    const lines = [
      "export function firstSymbol() { return 1; }",
      ...Array(120).fill("// filler"),
      "export function secondSymbol() { return 2; }",
    ];
    const result = await retrieveContext(
      memoryWorkspace({ "src/features.ts": lines.join("\n") }),
      "Read @symbol:firstSymbol and @symbol:secondSymbol",
      8192,
    );
    expect(result.snippets.map((snippet) => snippet.text).join("\n")).toContain(
      "function firstSymbol",
    );
    expect(result.snippets.map((snippet) => snippet.text).join("\n")).toContain(
      "function secondSymbol",
    );
    expect(result.snippets).toHaveLength(2);
  });

  it("excludes source files identified as generated by their header", async () => {
    const adapter = memoryWorkspace({
      "src/generated.ts":
        "// @generated; do not edit\nexport const needle = true;",
      "src/real.ts": "export const needle = true;",
    });
    const result = await retrieveContext(adapter, "Find needle");
    expect(result.snippets.map((snippet) => snippet.path)).toEqual([
      "src/real.ts",
    ]);
  });

  it("discovers code, tests and docs from task language without hardcoded project paths", async () => {
    const adapter = memoryWorkspace({
      "lib/command_registry.py":
        'def config_command():\n    """Print application configuration as JSON."""\n    return configuration',
      "checks/test_commands.py":
        'def test_config_command():\n    assert invoke("config").output == "{}"',
      "guide/terminal.md":
        "# Terminal\nThe config command displays configuration.",
      "lib/unrelated.py": "def render_image():\n    return pixels",
    });
    const result = await retrieveContext(
      adapter,
      "Add a CLI configuration command that prints JSON with tests and documentation",
    );
    expect(result.snippets.map((snippet) => snippet.path)).toEqual(
      expect.arrayContaining([
        "lib/command_registry.py",
        "checks/test_commands.py",
        "guide/terminal.md",
      ]),
    );
    expect(result.snippets.map((snippet) => snippet.path)).not.toContain(
      "lib/unrelated.py",
    );
    expect(
      new Set(
        result.snippets.map(
          (snippet) =>
            `${snippet.path}:${snippet.startLine}:${snippet.endLine}`,
        ),
      ).size,
    ).toBe(result.snippets.length);
  });

  it("never reads excluded files or returns binary text", async () => {
    const adapter = memoryWorkspace({
      ".env": "SECRET=needle",
      "node_modules/dependency.ts": "needle",
      "dist/bundle.js": "needle",
      "private.pem": "needle",
      "src/binary.ts": "\0needle",
      "src/safe.ts": "const needle = true;",
    });
    const result = await retrieveContext(adapter, "Find needle");
    expect(result.snippets.map((snippet) => snippet.path)).toEqual([
      "src/safe.ts",
    ]);
    expect(adapter.reads).not.toEqual(
      expect.arrayContaining([
        ".env",
        "node_modules/dependency.ts",
        "dist/bundle.js",
        "private.pem",
      ]),
    );
    await expect(retrieveContext(adapter, "Read @file:.env")).rejects.toThrow(
      /excluded/i,
    );
  });

  it("allocates estimated snippet input after instruction, system/tool and output reservations", async () => {
    const adapter = memoryWorkspace({
      "src/feature.ts": Array.from(
        { length: 100 },
        (_, i) => `const feature${i} = "${"data ".repeat(30)}";`,
      ).join("\n"),
    });
    const instruction = "Explain feature and propose changes";
    const result = await retrieveContext(adapter, instruction, 2400);
    const budget = calculateContextBudget(2400, instruction);
    expect(
      result.inputBudget +
        budget.instructionTokens +
        budget.schemaReserve +
        budget.outputReserve,
    ).toBeLessThanOrEqual(2400);
    expect(result.usedTokens).toBeLessThanOrEqual(result.inputBudget);
    expect(result.usedTokens).toBe(
      result.snippets.reduce((sum, snippet) => sum + snippet.tokenEstimate, 0),
    );
    expect(result.snippets.length).toBeGreaterThan(0);
    expect(result.snippets[0].text.length).toBeLessThan(
      adapter.files["src/feature.ts"].length,
    );
    expect(result.omittedCount).toBeGreaterThan(0);
  });

  it("leaves at most 1536 estimated snippet tokens minus instruction cost at the default context size", async () => {
    const adapter = memoryWorkspace({
      "src/config.ts": Array.from(
        { length: 100 },
        (_, index) => `const config${index} = "${"value ".repeat(20)}";`,
      ).join("\n"),
    });
    // Six UTF-8 bytes estimate to two instruction tokens independently of budget calculation.
    const result = await retrieveContext(adapter, "config", 4096);
    expect(result.inputBudget).toBeLessThanOrEqual(1534);
    expect(result.usedTokens).toBeLessThanOrEqual(1534);
    expect(result.snippets.length).toBeGreaterThan(0);
    expect(result.omittedCount).toBeGreaterThan(0);
  });

  it("avoids workspace reads when system/tool and output reserves consume a small context", async () => {
    const adapter = memoryWorkspace({
      "src/config.ts": "const config = true;",
    });
    const result = await retrieveContext(adapter, "config", 2048);
    expect(result).toMatchObject({
      snippets: [],
      usedTokens: 0,
      inputBudget: 0,
    });
    expect(adapter.reads).toHaveLength(0);
  });

  it("does no reads when the request leaves no input budget", async () => {
    const adapter = memoryWorkspace({
      "src/config.ts": "const config = true;",
    });
    const result = await retrieveContext(adapter, "config ".repeat(2000), 1024);
    expect(result).toMatchObject({
      snippets: [],
      usedTokens: 0,
      inputBudget: 0,
    });
    expect(adapter.reads).toHaveLength(0);
  });

  it("returns a useful error for unresolved explicit file mentions", async () => {
    await expect(
      retrieveContext(memoryWorkspace({}), "Read @file:src/missing.ts"),
    ).rejects.toThrow(/mentioned.*not found/i);
  });

  it("returns bounded structured literal search results with one-based line numbers", async () => {
    const adapter = memoryWorkspace({
      "src/feature.ts": `first\r\nconst literal = "a+b";\r\n${"a+b ".repeat(1000)}`,
    });
    const result = await searchWorkspace(adapter, "a+b", 1);
    expect(result).toHaveLength(1);
    expect(result[0]).toEqual({
      path: "src/feature.ts",
      line: 2,
      text: 'const literal = "a+b";',
    });
    const longer = await searchWorkspace(adapter, "a+b", 1000);
    expect(longer[1].text.length).toBeLessThanOrEqual(240);
    expect(await searchWorkspace(adapter, "[absent")).toEqual([]);
  });

  it("bounds file reads and scanned prefixes on large workspaces", async () => {
    const files = Object.fromEntries(
      Array.from({ length: 600 }, (_, i) => [`src/module-${i}.ts`, "needle"]),
    );
    const adapter = memoryWorkspace(files);
    const result = await searchWorkspace(adapter, "needle", 1000);
    expect(result.length).toBeLessThanOrEqual(100);
    expect(adapter.reads.length).toBeLessThanOrEqual(256);
    const large = memoryWorkspace({
      "src/large.ts": "x".repeat(100_000) + "\nneedle after limit",
    });
    expect(await searchWorkspace(large, "needle")).toEqual([]);
  });

  it("refreshes an incrementally cached file when a later request grants a larger scan prefix", async () => {
    const fullPrefix = ("// " + "x".repeat(96) + "\n").repeat(656);
    const files: Record<string, string> = Object.fromEntries(
      Array.from({ length: 15 }, (_, index) => [
        `src/a-${index}.ts`,
        fullPrefix,
      ]),
    );
    files["src/b.ts"] = "x".repeat(1000);
    files["src/specialSymbol.ts"] =
      ("// " + "x".repeat(96) + "\n").repeat(650) +
      "export function specialSymbol() {}";
    const adapter = memoryWorkspace(files);
    await searchWorkspace(adapter, "absent");
    const result = await searchWorkspace(adapter, "specialSymbol");
    expect(result).toContainEqual({
      path: "src/specialSymbol.ts",
      line: 651,
      text: "export function specialSymbol() {}",
    });
  });
});
